export const TINY_MP4_BASE64 = BASE64_LINES.join("");

/** Decodes the embedded fixture bytes (a fresh allocation per call). */
export function tinyMp4Bytes(): Uint8Array {
  return new Uint8Array(Buffer.from(TINY_MP4_BASE64, "base64"));
}

/**
 * Writes the fixture into `dir` (which must already exist) under
 * {@link TINY_MP4_FILENAME} and returns the absolute file path.
 */
export function writeTinyMp4(dir: string): string {
  const filePath = path.join(dir, TINY_MP4_FILENAME);
  writeFileSync(filePath, tinyMp4Bytes());
  return filePath;
}

