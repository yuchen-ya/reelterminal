import { expect, test } from "vitest";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { launchApp } from "./harness/launch";
import { createProjectViaUI } from "./harness/ui";
import { createEvidence } from "./harness/evidence";

test("compact instructions copy through the library and settings expose Agent configuration", async () => {
  const configDir = mkdtempSync(path.join(tmpdir(), "rt-environment-e2e-"));
  const configPath = path.join(configDir, "audio.json");
  writeFileSync(configPath, JSON.stringify({ python: path.join(configDir, "missing-python.exe"), separationPython: path.join(configDir, "missing-separation.exe") }));
  const launched = await launchApp({ env: { REELTERMINAL_AUDIO_CONFIG: configPath } });
  const page = launched.page;
  const evidence = createEvidence("instruction-library-environment", page);
  try {
    await createProjectViaUI(page);
    await page.getByRole("button", { name: "Board", exact: true }).click();
    const board = page.getByTestId("collaboration-board");
    const add = board.getByRole("button", { name: "Add instruction", exact: true });
    expect(await add.count()).toBe(1);
    expect(await board.getByRole("button", { name: "New instruction" }).count()).toBe(0);
    await page.waitForTimeout(250);
    await evidence.screenshot("empty");
    await add.click();
    let picker = page.getByRole("dialog", { name: "Add instruction", exact: true });
    await picker.getByRole("button", { name: "Guide me visually", exact: true }).waitFor();
    await page.waitForTimeout(250);
    await evidence.screenshot("selector");
    await picker.getByRole("button", { name: "Guide me visually", exact: true }).click();
    const chip = board.getByRole("button", { name: "Guide me visually", exact: true });
    await chip.waitFor();
    expect(await page.getByRole("textbox", { name: "Title", exact: true }).count()).toBe(0);
    await chip.click();
    let editor = page.getByRole("dialog", { name: "Edit instruction", exact: true });
    await editor.getByRole("textbox", { name: "Title", exact: true }).fill("Preview first");
    await page.waitForTimeout(250);
    await evidence.screenshot("editor");
    await editor.getByRole("button", { name: "Save changes" }).click();
    const renamed = board.getByRole("button", { name: "Preview first", exact: true });
    await renamed.click({ button: "right" });
    await page.getByRole("menuitem", { name: "Save to library" }).click();
    await board.getByRole("status").getByText("Saved", { exact: true }).waitFor();
    await add.click();
    picker = page.getByRole("dialog", { name: "Add instruction", exact: true });
    await picker.getByRole("textbox", { name: "Search instructions" }).fill("Preview first");
    expect(await picker.getByRole("button", { name: "Preview first", exact: true }).isDisabled()).toBe(true);
    await picker.getByRole("textbox", { name: "Search instructions" }).fill("no-such-instruction");
    await picker.getByText("No matching instructions").waitFor();
    await picker.getByRole("button", { name: "New instruction", exact: true }).click();
    editor = page.getByRole("dialog", { name: "New instruction", exact: true });
    await editor.getByRole("textbox", { name: "Title", exact: true }).fill("Project copy");
    await editor.getByRole("textbox", { name: "Detailed instruction" }).fill("Keep approved work unchanged.");
    await editor.getByRole("button", { name: "Add to project" }).click();
    const second = board.getByRole("button", { name: "Project copy", exact: true });
    await second.waitFor();
    await second.press("Alt+ArrowLeft");
    await page.waitForTimeout(250);
    await evidence.screenshot("compact-board");
    await second.click({ button: "right" });
    await page.getByRole("menuitem", { name: "Disable", exact: true }).click();
    expect(await board.getByRole("switch", { name: "Enable Project copy" }).getAttribute("aria-checked")).toBe("false");
    await second.click({ button: "right" });
    await page.getByRole("menuitem", { name: "Delete instruction" }).click();
    await second.waitFor({ state: "hidden" });
    await renamed.focus();
    await page.keyboard.press("Meta+z");
    await second.waitFor();
    await add.click();
    await page.keyboard.press("Escape");
    await expect.poll(() => add.evaluate(element => document.activeElement === element)).toBe(true);
    await page.getByRole("button", { name: "Settings", exact: true }).click();
    const settings = page.getByRole("dialog", { name: "Settings", exact: true });
    await settings.getByRole("radio", { name: "Models & environment", exact: true }).click();
    await settings.getByText("Configuration required", { exact: true }).first().waitFor();
    await settings.getByRole("button", { name: "Set up with Agent" }).click();
    await settings.getByRole("button", { name: "Copy setup prompt" }).click();
    await settings.getByText("Copied", { exact: true }).waitFor();
    const prompt = await launched.app.evaluate(({ clipboard }) => clipboard.readText());
    expect(prompt).toContain("environment set --file config.json");
    expect(prompt).toContain("environment test --file speech.wav");
    await page.waitForTimeout(250);
    await evidence.screenshot("model-environment");
    evidence.record("copiedPromptHasCliAcceptance", true);
    evidence.flush();
  } catch (error) {
    await evidence.screenshot("failure");
    throw error;
  } finally {
    await launched.close();
    rmSync(configDir, { recursive: true, force: true });
  }
}, 120_000);
